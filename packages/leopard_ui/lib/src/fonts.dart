abstract final class LeopardFonts {
  static const String _prefix = 'packages/leopard_ui/';

  /// Body text (400, 500, 600).
  static const String body = '${_prefix}Inter';

  /// Headings (500, 600, 700).
  static const String heading = '${_prefix}SpaceGrotesk';

  /// Secrets and codes (500, 600).
  static const String mono = '${_prefix}JetBrainsMono';
}
