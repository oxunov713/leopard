var updateVectors = flag.Bool("update-vectors", false, "rewrite docs/test-vectors.json instead of comparing")

const vectorsPath = "../../../docs/test-vectors.json"

func seq(start byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = start + byte(i)
	}
	return b
}

func hx(b []byte) string { return hex.EncodeToString(b) }

func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

type kv = map[string]any

// buildVectors recomputes every vector from fixed inputs. The inputs are
// deliberately trivial patterns; never use them for anything real.
func buildVectors() kv {
	vk := seq(0x00, 32)
	itemID := "0f8fad5b-d9cb-469f-a165-70867728950e"
	itemVersion := uint64(7)
	itemNonce := seq(0xa0, 12)
	itemPlain := []byte(`{"type":"login","title":"Example","fields":{"username":"aziz","password":"correct horse battery staple","url":"https://example.com"}}`)
	itemKey := must(DeriveItemKey(vk))
	itemAAD := must(ItemAAD(itemID, itemVersion))
	itemCT := must(SealItem(itemKey, itemNonce, itemID, itemVersion, itemPlain))

	params := DefaultKDFParams()
	password := "correct horse battery staple — Ünïcödé ✓"
	salt := seq(0x10, 16)
	kek := must(DeriveKEK([]byte(password), salt, params))
	wrapNonce := seq(0xb0, 12)
	wrappedMaster := must(WrapVK(kek, wrapNonce, vk, InfoWrapMaster))
	authKey := must(MasterAuthKey(kek))

	rk := seq(0x20, 16)
	rkDisplay := must(FormatRecoveryKey(rk))
	rkKEK := must(RecoveryKEK(rk))
	rkNonce := seq(0xc0, 12)
	wrappedRecovery := must(WrapVK(rkKEK, rkNonce, vk, InfoWrapRecovery))
	rkAuth := must(RecoveryAuthKey(rk))

	browserPriv := seq(0x30, 32)
	phonePriv := seq(0x50, 32)
	browserPub := must(X25519Public(browserPriv))
	phonePub := must(X25519Public(phonePriv))
	shared := must(X25519Shared(phonePriv, browserPub))
	sid := seq(0x70, 16)
	qrKey := must(QRTransferKey(shared, sid, browserPub, phonePub))
	qrNonce := seq(0xd0, 12)
	qrCT := must(QRSealVK(phonePriv, browserPub, sid, qrNonce, vk))
	deviceSeed := seq(0x80, 32)
	devicePriv := ed25519.NewKeyFromSeed(deviceSeed)
	devicePub := devicePriv.Public().(ed25519.PublicKey)
	approveMsg := must(QRApproveMessage(sid, browserPub, phonePub, qrNonce, qrCT))
	approveSig := ed25519.Sign(devicePriv, approveMsg)
	verifyCode := must(VerifyCode(sid, browserPub))

	deviceID := "7c9e6679-7425-40de-944b-e07fc1f90ae7"
	challenge := seq(0xe0, 32)
	authMsg := must(DeviceAuthMessage(deviceID, challenge))
	authSig := ed25519.Sign(devicePriv, authMsg)

	totpSecret := []byte("12345678901234567890")
	var totpCases []kv
	for _, u := range []int64{59, 1111111109, 1234567890, 2000000000} {
		totpCases = append(totpCases, kv{"unix_time": u, "step": totp.Step(time.Unix(u, 0)), "code": totp.Code(totpSecret, time.Unix(u, 0))})
	}

	return kv{
		"_comment": "Leopard crypto test vectors, generated by backend/internal/crypto/vectors_test.go. Binary values are lower-case hex here (the wire format is base64url without padding; see the encoding section). Inputs are fixed patterns and MUST NOT be used as real keys.",
		"version":  1,
		"encoding": kv{
			"bytes_hex":      hx([]byte{0xfb, 0xff, 0xfe, 0x00, 0x01}),
			"base64url":      B64([]byte{0xfb, 0xff, 0xfe, 0x00, 0x01}),
			"vk_hex":         hx(vk),
			"vk_base64url":   B64(vk),
			"note":           "base64url alphabet (RFC 4648 section 5), no '=' padding",
			"sha256_abc_hex": hx(SHA256([]byte("abc"))),
		},
		"item_key": kv{
			"vk_hex":       hx(vk),
			"salt_hex":     "",
			"info":         InfoItem,
			"item_key_hex": hx(itemKey),
		},
		"item_encryption": kv{
			"item_key_hex":   hx(itemKey),
			"item_id":        itemID,
			"version":        itemVersion,
			"nonce_hex":      hx(itemNonce),
			"plaintext_utf8": string(itemPlain),
			"aad_hex":        hx(itemAAD),
			"ciphertext_hex": hx(itemCT),
			"note":           "ciphertext_hex is AES-GCM ciphertext followed by the 16-byte tag",
		},
		"master_password": kv{
			"password_utf8":         password,
			"password_utf8_hex":     hx([]byte(password)),
			"salt_hex":              hx(salt),
			"kdf_params":            params,
			"kek_hex":               hx(kek),
			"wrap_nonce_hex":        hx(wrapNonce),
			"wrap_aad":              InfoWrapMaster,
			"vk_hex":                hx(vk),
			"wrapped_vk_master_hex": hx(wrappedMaster),
			"auth_info":             InfoAuthMaster,
			"auth_key_hex":          hx(authKey),
			"auth_verifier_hex":     hx(AuthVerifier(authKey)),
			"note":                  "wrapped_vk_master is nonce(12) || ciphertext(32) || tag(16); auth_verifier is SHA-256(auth_key)",
		},
		"recovery_key": kv{
			"rk_hex":                  hx(rk),
			"display":                 rkDisplay,
			"kek_info":                InfoWrapRecovery,
			"kek_hex":                 hx(rkKEK),
			"wrap_nonce_hex":          hx(rkNonce),
			"wrap_aad":                InfoWrapRecovery,
			"vk_hex":                  hx(vk),
			"wrapped_vk_recovery_hex": hx(wrappedRecovery),
			"auth_info":               InfoAuthRecovery,
			"auth_key_hex":            hx(rkAuth),
			"auth_verifier_hex":       hx(AuthVerifier(rkAuth)),
		},
		"qr_transfer": kv{
			"browser_priv_hex":      hx(browserPriv),
			"browser_pub_hex":       hx(browserPub),
			"phone_eph_priv_hex":    hx(phonePriv),
			"phone_eph_pub_hex":     hx(phonePub),
			"shared_secret_hex":     hx(shared),
			"sid_hex":               hx(sid),
			"sid_base64url":         B64(sid),
			"hkdf_salt_hex":         hx(sid),
			"hkdf_info_hex":         hx(append(append([]byte(InfoQR), browserPub...), phonePub...)),
			"transfer_key_hex":      hx(qrKey),
			"nonce_hex":             hx(qrNonce),
			"aad_hex":               hx(sid),
			"vk_hex":                hx(vk),
			"ciphertext_hex":        hx(qrCT),
			"device_seed_hex":       hx(deviceSeed),
			"device_pub_hex":        hx(devicePub),
			"approve_message_hex":   hx(approveMsg),
			"approve_signature_hex": hx(approveSig),
			"verify_code":           verifyCode,
			"qr_uri":                QRURI(sid, browserPub),
		},
		"device_auth": kv{
			"device_id":       deviceID,
			"device_seed_hex": hx(deviceSeed),
			"device_pub_hex":  hx(devicePub),
			"challenge_hex":   hx(challenge),
			"message_hex":     hx(authMsg),
			"signature_hex":   hx(authSig),
		},
		"totp": kv{
			"secret_ascii": string(totpSecret),
			"secret_hex":   hx(totpSecret),
			"algorithm":    "SHA1",
			"period":       totp.Period,
			"digits":       totp.Digits,
			"cases":        totpCases,
		},
	}
}

func marshalVectors(t *testing.T) []byte {
	t.Helper()
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(buildVectors()); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// TestVectorsUnchanged fails if the implementation no longer reproduces
// docs/test-vectors.json. Run `go test ./internal/crypto -update-vectors`
// only for a deliberate, versioned protocol change.
func TestVectorsUnchanged(t *testing.T) {
	got := marshalVectors(t)
	path := filepath.FromSlash(vectorsPath)
	if *updateVectors {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", path)
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read vectors (run with -update-vectors to create): %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("recomputed vectors differ from %s; the protocol output changed", path)
	}
}

// TestVectorsSelfConsistent decrypts and verifies everything in the committed
// file using only the values in the file, the way a second implementation would.
func TestVectorsSelfConsistent(t *testing.T) {
	raw, err := os.ReadFile(filepath.FromSlash(vectorsPath))
	if err != nil {
		t.Skipf("no vectors file: %v", err)
	}
	var v map[string]map[string]any
	// "version" and "_comment" are scalars; decode loosely first.
	var loose map[string]json.RawMessage
	if err := json.Unmarshal(raw, &loose); err != nil {
		t.Fatal(err)
	}
	v = map[string]map[string]any{}
	for k, m := range loose {
		var sec map[string]any
		if json.Unmarshal(m, &sec) == nil {
			v[k] = sec
		}
	}
	h := func(sec, key string) []byte {
		s, ok := v[sec][key].(string)
		if !ok {
			t.Fatalf("missing %s.%s", sec, key)
		}
		return must(hex.DecodeString(s))
	}
	str := func(sec, key string) string { return v[sec][key].(string) }

	// Items.
	pt, err := OpenItem(h("item_encryption", "item_key_hex"), h("item_encryption", "nonce_hex"),
		str("item_encryption", "item_id"), uint64(v["item_encryption"]["version"].(float64)), h("item_encryption", "ciphertext_hex"))
	if err != nil || string(pt) != str("item_encryption", "plaintext_utf8") {
		t.Fatalf("item vector does not decrypt: %v", err)
	}
	// Master wrap.
	vk, err := UnwrapVK(h("master_password", "kek_hex"), h("master_password", "wrapped_vk_master_hex"), InfoWrapMaster)
	if err != nil || !bytes.Equal(vk, h("master_password", "vk_hex")) {
		t.Fatalf("master wrap vector: %v", err)
	}
	if !CheckAuthKey(h("master_password", "auth_key_hex"), h("master_password", "auth_verifier_hex")) {
		t.Fatal("master auth verifier mismatch")
	}
	// Recovery.
	rk, err := ParseRecoveryKey(str("recovery_key", "display"))
	if err != nil || !bytes.Equal(rk, h("recovery_key", "rk_hex")) {
		t.Fatalf("recovery display: %v", err)
	}
	vk, err = UnwrapVK(must(RecoveryKEK(rk)), h("recovery_key", "wrapped_vk_recovery_hex"), InfoWrapRecovery)
	if err != nil || !bytes.Equal(vk, h("recovery_key", "vk_hex")) {
		t.Fatalf("recovery wrap vector: %v", err)
	}
	// QR: the browser side must recover VK from what the phone produced.
	vk, err = QROpenVK(h("qr_transfer", "browser_priv_hex"), h("qr_transfer", "phone_eph_pub_hex"),
		h("qr_transfer", "sid_hex"), h("qr_transfer", "nonce_hex"), h("qr_transfer", "ciphertext_hex"))
	if err != nil || !bytes.Equal(vk, h("qr_transfer", "vk_hex")) {
		t.Fatalf("qr vector: %v", err)
	}
	if !Ed25519Verify(h("qr_transfer", "device_pub_hex"), h("qr_transfer", "approve_message_hex"), h("qr_transfer", "approve_signature_hex")) {
		t.Fatal("qr approve signature does not verify")
	}
	if !Ed25519Verify(h("device_auth", "device_pub_hex"), h("device_auth", "message_hex"), h("device_auth", "signature_hex")) {
		t.Fatal("device auth signature does not verify")
	}
}
